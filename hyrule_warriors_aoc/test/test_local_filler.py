class TestLocalFillerMultiworld(TestCase):
    def test_fuzz_seed_17_fills(self) -> None:
        world = AutoWorldRegister.world_types["Hyrule Warriors Age of Calamity"]
        multiworld = setup_multiworld([world] * 3, seed=17, options=FUZZ_17)
        locality_rules(multiworld)  # (as Main does: local_filler keeps each filler in its own world)
        distribute_items_restrictive(multiworld)  # (raised FillError before the fix)
        call_all(multiworld, "post_fill")
        for loc in multiworld.get_locations():
            item = loc.item
            self.assertIsNotNone(item, loc.name)
            if item.classification == ItemClassification.filler and item.player != loc.player:
                self.assertFalse(multiworld.worlds[item.player].options.local_filler, (item.name, loc.name))
